#!/usr/bin/env python3
"""Build the web app: src/*.js + src/style.css -> docs/index.html (GitHub Pages root).

Workers and audio worklets cannot be inlined into the page, so they are copied next to it (docs/<name>);
the bundle gets their URLs with a content hash (ASSET) so a new build is never served a stale worker.
Also writes the concatenated bundle to .work/bundle.js so it can be syntax-checked with
`node --check .work/bundle.js`. docs/ is build output: edit src/, never docs/index.html.
docs/voices/ (tools/tts/packgen.py) and docs/vendor/ (tools/vendor.py) are generated by their own tools.
"""
import hashlib, json, os, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
WORK = pathlib.Path(os.environ.get('ATC_WORK', ROOT / '.work'))
SRC = ROOT / 'src'
DOCS = ROOT / 'docs'

# Order matters: every file defines globals used by the files after it.
ORDER = ['data.js', 'core.js', 'sim.js', 'phrase.js', 'voiceparse.js', 'audio.js', 'voicepack.js', 'tts.js', 'voice.js', 'llm.js', 'radar.js',
         'ground.js', 'window.js', 'strips.js', 'tests.js', 'app.js']
# Served as separate files next to index.html.
COPY = ['asr-worker.js', 'mic-worklet.js', 'tts-worker.js', 'llm-worker.js']

asset = {}
for n in COPY:
    b = (SRC / n).read_bytes(); (DOCS / n).write_bytes(b)
    asset[n] = f'{n}?v={hashlib.sha256(b).hexdigest()[:10]}'
head = f'/* ---- build ---- */\nconst ASSET = {json.dumps(asset)};\n'
js = head + '\n'.join(f'/* ---- {n} ---- */\n' + (SRC / n).read_text() for n in ORDER)
if '</script' in js.lower():
    sys.exit('JS contains </script')
html = (SRC / 'template.html').read_text().replace('/*__CSS__*/', (SRC / 'style.css').read_text()).replace('/*__JS__*/', js)
out = DOCS / 'index.html'
out.write_text(html)
WORK.mkdir(parents=True, exist_ok=True)
(WORK / 'bundle.js').write_text(js)
print('built', out.relative_to(ROOT), len(html) // 1024, 'KB +', ', '.join(COPY))
